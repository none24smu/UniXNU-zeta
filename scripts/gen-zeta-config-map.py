#!/usr/bin/env python3
"""Generate the zeta ConfigurationMapLib.c from the numeric [ConfigParameters] of the stock uefiplat.cfg.

String parameters (OsTypeString, DefaultBDSBootApp, ...) are not representable by the numeric
configuration library and are left out. The overrides below are the single-core, headless first-boot
settings sheng uses without the vendor drivers; NumCpus keeps the real eight-core topology.
Output: ../uefi-zeta/Platforms/Microsoft/zetaPkg/Library/ConfigurationMapLib/ConfigurationMapLib.c
"""
import hashlib
import os
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
# Run from the build tree, the device repository is the one "unixnu tree" linked .cache/firmware to.
ROOT = (HERE / '.cache/firmware').resolve().parents[1] if (HERE / '.cache/firmware').is_symlink() else HERE
UEFI = Path(os.environ.get('UNIXNU_UEFI') or ROOT / '../uefi-zeta').resolve()
CONFIG = ROOT / '.cache/firmware/zeta/uefiplat.cfg'
OUTPUT = UEFI / 'Platforms/Microsoft/zetaPkg/Library/ConfigurationMapLib/ConfigurationMapLib.c'
SKIP = ('ConfigParameterCount',)
OVERRIDES = {
    'NumActiveCores': 0x1,
    'EarlyInitCoreCnt': 0x1,
    'EnableMultiThreading': 0x0,
    'EnableMultiCoreFvDecompression': 0x0,
    'EnableDisplayThread': 0x0,
    'EnableDisplayImageFv': 0x0,
    'EnableLogFsSyncInRetail': 0x0,
}


def render():
    text = CONFIG.read_text().split('[ConfigParameters]', 1)[1]
    values = {}
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        if '=' not in line:
            continue
        name, value = (part.strip() for part in line.split('=', 1))
        if name in SKIP or value.startswith('"'):
            continue
        values[name] = int(value, 0)
    missing = sorted(set(OVERRIDES) - set(values))
    if missing:
        raise SystemExit(f'stock map lacks the overridden parameters {missing}')
    values.update(OVERRIDES)
    lines = ['// SPDX-License-Identifier: BSD-2-Clause-Patent',
             '// Generated by UniXNU-zeta scripts/gen-zeta-config-map.py; do not edit.',
             f'// Stock parameters: uefiplat.cfg sha256 {hashlib.sha256(CONFIG.read_bytes()).hexdigest()}.',
             f'// First-boot overrides: {", ".join(sorted(OVERRIDES))}.',
             '#include <Library/ConfigurationMapLib.h>', '', 'STATIC', 'EFI_CONFIGURATION_ENTRY_DESCRIPTOR',
             'gConfigurationDescriptor[] = {']
    names = sorted(values)
    for index, name in enumerate(names):
        lines.append(f'  {{"{name}", 0x{values[name]:X}}}{"," if index + 1 < len(names) else ""}')
    lines += ['};', '', 'VOID', 'GetConfigurationMap (',
              '  OUT EFI_CONFIGURATION_ENTRY_DESCRIPTOR **ConfigurationDescriptor,',
              '  OUT UINT8                               *ConfigurationDescriptorCount)', '{',
              '  // Pass Data', '  *ConfigurationDescriptor      = gConfigurationDescriptor;',
              '  *ConfigurationDescriptorCount = ARRAY_SIZE (gConfigurationDescriptor);', '}', '']
    return '\n'.join(lines), f'{len(names)} numeric parameters ({len(OVERRIDES)} overridden)'


def main():
    text, summary = render()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f'{summary} -> {OUTPUT}')


if __name__ == '__main__':
    main()
